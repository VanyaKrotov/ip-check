if (!i18n.isInitialized) {
  i18n
    .use(initReactI18next)
    .init({
      resources,
      supportedLngs: supportedLanguages,
      fallbackLng: "en",
      lng:
        typeof window !== "undefined" && window.localStorage.getItem("ip-check-language-source") === "manual"
          ? window.localStorage.getItem("i18nextLng") || "en"
          : "en",
      interpolation: {
        escapeValue: false,
      },
    });
}

export function hasExplicitLanguage() {
  if (typeof window === "undefined") {
    return false;
  }

  return window.localStorage.getItem("ip-check-language-source") === "manual";
}

export function markLanguageManual(language: string) {
  if (typeof window !== "undefined") {
    window.localStorage.setItem("ip-check-language-source", "manual");
    window.localStorage.setItem("i18nextLng", language);
  }
}

export default i18n;
